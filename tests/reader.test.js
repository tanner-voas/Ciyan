test('focus cards are sampled six times more often than normal vocabulary, and early practice remains provisional',()=>{
 const s=defaultState();acceptChapter(s,...chapters[0]);
 const b=s.reader.panlong,c=b.chapters[0],now=Date.now(),session=new Map();
 const term=c.focus.find(k=>b.items[k].kind==='term');const vocab=c.all.find(k=>b.items[k].kind==='vocab'&&k==='vocab-斑驳');
 const a=readerAnalysis(s,b,c,now,session);
 const choices=[vocab,term];
 const n=7000;let focusCount=0;
 for(let i=0;i<n;i++)if(pickReaderItem(choices,a,()=>i/n)===term)focusCount++;
 assert.ok(focusCount/n>.84&&focusCount/n<.87,'Focused item should occupy six of seven weighted slots');
 gradeReader(s,b,term,1,now);
 const saved=JSON.stringify(s);
 for(const grade of [3,2,3]){
  assert.equal(gradeReader(s,b,term,grade,now+1),false);
  recordPractice(session,term,grade);
 }
 assert.ok(readerAnalysis(s,b,c,now+1,session).weak.includes(term));
 recordPractice(session,term,3);
 assert.ok(!readerAnalysis(s,b,c,now+1,session).weak.includes(term));
 assert.ok(readerAnalysis(s,b,c,now+1,new Map()).weak.includes(term));
 assert.equal(JSON.stringify(s),saved);
 gradeReader(s,b,vocab,1,now);
 const before=JSON.stringify(s);assert.equal(gradeReader(s,b,vocab,4,now+1),false);
 assert.equal(JSON.stringify(s),before);
 const due=Date.parse(b.progress[term].dueAt);
 const scheduled=readerAnalysis(s,b,c,due,session);
 assert.deepEqual(scheduled.queue.map(scheduled.group),scheduled.queue.map(scheduled.group).sort());
 recordPractice(session,vocab,4);assert.ok(!readerAnalysis(s,b,c,now,session).weak.includes(vocab));
});
