// Deterministically generate character-specific CSS @font-face unicode ranges.
// In contrast to wrapping every Hanzi in spans, the browser handles matching
// natively and the DOM remains unchanged even on large lists/reader chapters.
import fs from 'node:fs';
import {FONT_CATALOG,FONT_LEVELS,FONT_LEVEL_FACES,fontSources,mixIndex} from './fonts.js';
const cjk='U+2E80-2EFF,U+3000-303F,U+3400-4DBF,U+4E00-9FFF,U+F900-FAFF,U+20000-2FA1F';
const lines=['/* Auto-generated by node build_mixed_fonts.mjs. No font binaries embedded. */'];
lines.push(`@font-face{font-family:'CiyanPrint';src:local('PingFang SC'),local('Noto Sans CJK SC'),local('Microsoft YaHei');unicode-range:${cjk};}`);
for(const [id,entry] of Object.entries(FONT_CATALOG))lines.push(`@font-face{font-family:'${entry.face}';src:${fontSources(id)};unicode-range:${cjk};}`);
function formatPoints(points){const out=[];let lo=null,hi=null;
 for(const n of points){if(lo===null){lo=n;hi=n;}else if(n===hi+1)hi=n;else{out.push(`U+${lo.toString(16).toUpperCase()}${lo===hi?'':'-'+hi.toString(16).toUpperCase()}`);lo=n;hi=n;}}
 if(lo!==null)out.push(`U+${lo.toString(16).toUpperCase()}${lo===hi?'':'-'+hi.toString(16).toUpperCase()}`);return out.join(',');}
const points=[[],[]];for(let cp=0x3400;cp<=0x9FFF;cp++){
 if(cp>0x4DBF&&cp<0x4E00)continue;points[mixIndex(cp)].push(cp);
}
for(let cp=0xF900;cp<=0xFAFF;cp++)points[mixIndex(cp)].push(cp);
const subsets=points.map(formatPoints);
for(const [level,options] of Object.entries(FONT_LEVELS)){
 if(level==='beginner')continue;
 const pool=options.map(([id])=>id).filter(id=>id!=='mixed');
 for(let i=0;i<pool.length;i++)lines.push(`@font-face{font-family:'${FONT_LEVEL_FACES[level]}';src:${fontSources(pool[i])};unicode-range:${subsets[i]};}`);
}
fs.writeFileSync(new URL('./mixed-fonts.css',import.meta.url),lines.join('\n')+'\n');
console.log('Mixed font CSS generated; size',fs.statSync(new URL('./mixed-fonts.css',import.meta.url)).size);
